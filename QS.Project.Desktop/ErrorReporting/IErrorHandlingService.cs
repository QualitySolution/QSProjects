using System;

namespace QS.ErrorReporting {

	/// <summary>
	/// Единая точка разбора исключений. Сначала ошибку предлагают цепочке <see cref="IErrorHandler"/>:
	/// знакомый класс ошибок разбирается там и получает понятный пользователю текст.
	/// Всё, что никто не узнал, показывается как непредвиденная ошибка с предложением
	/// отправить отчёт разработчикам через <see cref="IErrorReporter"/>.
	///
	/// Ставится и глобальным перехватчиком, и в тех местах, где после сбоя операция
	/// обязана продолжиться: там локальный catch нужен не «чтобы не падало», а чтобы
	/// приложить к ошибке заголовок операции и отдать её сюда.
	/// </summary>
	public interface IErrorHandlingService {

		/// <param name="operationTitle">
		/// Заголовок сообщения - что именно не получилось: «Удаление базы данных», «Управление пользователями».
		/// </param>
		void Handle(Exception exception, string operationTitle = null);
	}
}

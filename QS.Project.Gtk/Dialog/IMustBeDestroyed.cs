using System;
namespace QS.Dialog.GtkUI
{
	/// <summary>
	/// Используется для вложенных GTK-виджетов, которые необходимо явно уничтожить
	/// при закрытии содержащего их диалога. GTK не всегда вызывает <c>Destroy()</c>
	/// для всех дочерних виджетов, поэтому код закрытия обходит дерево виджетов
	/// и уничтожает реализации этого интерфейса.
	/// Не применяйте интерфейс к диалогам и вкладкам: их должен уничтожать
	/// непосредственно код, управляющий их закрытием.
	/// </summary>
	public interface IMustBeDestroyed
	{
		void Destroy();
	}
}
